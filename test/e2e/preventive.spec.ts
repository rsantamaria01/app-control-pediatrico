import { expect, test } from '@playwright/test'
import { hashPassword } from 'better-auth/crypto'
import { drizzle } from 'drizzle-orm/node-postgres'
import { migrate } from 'drizzle-orm/node-postgres/migrator'
import { Pool } from 'pg'
import { account, catalogItem, catalogRelease, guardianGrant, patient, user, userRole } from '../../server/db/schema'

const enabled = process.env.AUTH_E2E === '1' && process.env.CLINICAL_E2E === '1' && process.env.CLINICAL_E2E_DATABASE_URL === process.env.TEST_DATABASE_URL
const url = process.env.TEST_DATABASE_URL

test.describe('preventive main flow on isolated database', () => {
  test.skip(!enabled, 'Requires disposable clinical E2E database')
  let pool: Pool
  test.beforeAll(async () => {
    if (!url || new URL(url).pathname !== '/pediatrico_auth_slice2_test' || url === process.env.DATABASE_URL) throw new Error('Dedicated disposable E2E DB required')
    pool = new Pool({ connectionString: url })
    await migrate(drizzle(pool), { migrationsFolder: './server/db/migrations' })
  })
  test.afterAll(async () => pool?.end())
  test('doctor records a dose, reviews complementary draft and verified contact; parent sees only applied dose', async ({ browser }) => {
    test.setTimeout(120_000)
    const db = drizzle(pool)
    const doctorId = crypto.randomUUID()
    const guardianId = crypto.randomUUID()
    const childId = crypto.randomUUID()
    const releaseId = crypto.randomUUID()
    const username = `prev-${doctorId.slice(0, 8)}`
    await db.insert(user).values([{ id: doctorId, name: 'Doctora', email: `${doctorId}@example.test`, username }, { id: guardianId, name: 'Representante', email: `${guardianId}@example.test`, username: `family-${guardianId.slice(0, 8)}` }])
    await db.insert(userRole).values([{ userId: doctorId, role: 'DOCTOR' }, { userId: guardianId, role: 'PATIENT' }])
    await db.insert(account).values([{ id: crypto.randomUUID(), userId: doctorId, accountId: doctorId, providerId: 'credential', password: await hashPassword('long secure password') }, { id: crypto.randomUUID(), userId: guardianId, accountId: guardianId, providerId: 'credential', password: await hashPassword('long family password') }])
    await db.insert(patient).values({ id: childId, name: 'Hija preventiva', birthDate: '2024-01-01', sex: 'FEMALE', createdBy: doctorId })
    await db.insert(guardianGrant).values({ patientId: childId, guardianId, contactEmail: `${guardianId}@example.test`, contactPhone: '0991234567', proof: 'Verificación presencial', verifiedBy: doctorId, status: 'ACTIVE' })
    await db.insert(catalogRelease).values({ id: releaseId, kind: 'VACCINE', publisher: 'MSP Ecuador', title: 'Fixture preventivo', version: `test-${releaseId}`, publicationDate: null, retrievedAt: '2026-11-16', url: 'https://www.salud.gob.ec/fixture.pdf', sha256: 'a'.repeat(64) })
    await db.insert(catalogItem).values({ releaseId, key: 'fixture-one', label: 'Vacuna fixture', domain: 'MSP', minAgeMonths: '12', maxAgeMonths: '12', sourcePage: 'p. 1', doseNumber: '1', recommendedAge: '12 meses' })
    const context = await browser.newContext({ viewport: { width: 375, height: 850 } })
    const page = await context.newPage()
    await page.goto('/acceso')
    await page.waitForLoadState('networkidle')
    await page.getByRole('textbox', { name: 'Usuario' }).fill(username)
    await page.getByLabel('Contraseña').fill('long secure password')
    await page.getByRole('button', { name: 'Ingresar' }).click()
    await expect(page).toHaveURL('/', { timeout: 10000 })
    await page.goto('/')
    await page.waitForLoadState('networkidle')
    await expect(page.getByRole('link', { name: 'Vacunación por revisar' })).toBeVisible()
    await page.goto('/pacientes/vacunacion-por-revisar')
    await page.waitForLoadState('networkidle')
    await expect(page.getByRole('link', { name: 'Hija preventiva' }).first()).toBeVisible()
    await expect(page.getByText('MSP · Vacuna fixture · Dosis 1').first()).toBeVisible()
    await expect(page.getByText('Representante · 0991234567', { exact: false }).first()).toBeVisible()
    await expect(page.getByText('Contacto registrado por personal clínico').first()).toBeVisible()
    await expect(page.getByText('Confirme el número y el canal con la familia antes de contactar.').first()).toBeVisible()
    await expect(page.getByRole('link', { name: 'Abrir WhatsApp (si usa este número)', exact: true }).first()).toHaveAttribute('href', 'https://wa.me/593991234567')
    await page.goto(`/pacientes/${childId}`)
    await page.waitForLoadState('networkidle')
    await expect(page.getByRole('heading', { name: 'Vacunas' })).toBeVisible()
    await page.getByRole('button', { name: '+ Vacuna complementaria' }).click()
    await page.getByRole('textbox', { name: 'Vacuna complementaria' }).fill('Complementaria fixture')
    await page.getByRole('textbox', { name: 'Dosis indicada' }).fill('Dosis individual')
    await page.getByRole('textbox', { name: 'Procedencia indicada por el médico' }).fill('Criterio de doctora fixture')
    await page.getByRole('button', { name: 'Guardar borrador' }).click()
    await expect(page.getByRole('table', { name: 'Vacunas por revisar' }).getByText('Complementaria fixture')).toBeVisible()
    await page.getByRole('button', { name: 'Registrar dosis' }).first().click()
    await page.getByRole('textbox', { name: 'Lote (privado)' }).fill('PRIVATE_LOT')
    await page.getByRole('textbox', { name: 'Nota clínica privada' }).fill('PRIVATE_NOTE')
    await page.getByRole('button', { name: 'Guardar dosis' }).click()
    await expect(page.getByText('PRIVATE_NOTE')).toBeVisible()
    await page.getByRole('button', { name: 'Desarrollo' }).click()
    await expect(page.getByText('No hay hitos OMS o CDC importados')).toBeVisible()
    await page.getByRole('button', { name: 'Controles', exact: true }).click()
    await expect(page.getByText('Fechas derivadas de las edades AAP en borrador', { exact: false })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(376)
    await context.clearCookies()
    await page.goto('/acceso')
    await page.waitForLoadState('networkidle')
    await page.getByRole('textbox', { name: 'Usuario' }).fill(`family-${guardianId.slice(0, 8)}`)
    await page.getByLabel('Contraseña').fill('long family password')
    await page.getByRole('button', { name: 'Ingresar' }).click()
    await expect(page).toHaveURL('/', { timeout: 10000 })
    await page.goto(`/hijos/${childId}`)
    await expect(page.getByRole('heading', { name: 'Vacunas aplicadas' })).toBeVisible()
    await expect(page.getByText('Vacuna fixture')).toBeVisible()
    expect(await page.locator('main').innerText()).not.toMatch(/PRIVATE_LOT|PRIVATE_NOTE|Complementaria fixture|0991234567/)
    expect((await context.request.get('/api/clinical/vacunacion-por-revisar')).status()).toBe(403)
    expect((await context.request.get(`/api/pacientes/${childId}/preventivo/vacunas`)).status()).toBe(403)
    expect((await context.request.get(`/api/hijos/${crypto.randomUUID()}/vacunas`)).status()).toBe(404)
    await context.close()
  })
})
